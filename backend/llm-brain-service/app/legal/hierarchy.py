import re
from dataclasses import dataclass

SOURCE = "ст. 10 Закона РК «О правовых актах» от 06.04.2016 № 480-V (в базе платформы закона нет — сверить)"

LEVELS: list[tuple[int, str]] = [
    (1, "Конституция Республики Казахстан"),
    (2, "законы о внесении изменений и дополнений в Конституцию"),
    (3, "конституционные законы и указы Президента, имеющие силу конституционного закона"),
    (4, "кодексы"),
    (5, "законы и указы Президента, имеющие силу закона"),
    (6, "нормативные постановления Парламента и его палат"),
    (7, "нормативные правовые указы Президента"),
    (8, "нормативные постановления Правительства"),
    (9, "нормативные правовые приказы министров и руководителей центральных госорганов"),
    (10, "нормативные правовые приказы руководителей ведомств"),
    (11, "нормативные решения маслихатов, акиматов и акимов"),
]
_NAMES = dict(LEVELS)

_PATTERNS: list[tuple[int, re.Pattern]] = [(lvl, re.compile(p, re.I | re.U)) for lvl, p in [
    (2, r"о\s+внесении\s+изменений[^.]{0,40}конституци"),
    (3, r"конституционн\w*\s+закон|силу\s+конституционного\s+закона"),
    (1, r"\bконституци"),
    (4, r"кодекс|^(?:тк|гк|нк|ук|упк|гпк|коап|пк|зк|эк|апк)\s+рк\b"),
    (5, r"\bзакон\b|\bзрк\b|^закон\s+рк|силу\s+закона|№\s*\d+-[IVXL]+(?:\s*ЗРК)?$"),
    (6, r"постановлени\w*\s+(?:парламента|сената|мажилиса)"),
    (7, r"\bуказ\w*\s+президента"),
    (8, r"постановлени\w*\s+правительства"),
    (9, r"приказ\w*\s+(?:министр|председател)"),
    (10, r"приказ\w*\s+(?:руководител|ведомств|комитет)"),
    (11, r"маслихат|акимат|\bаким\w*\s+решени|решени\w*\s+аким"),
]]

COLLISION_RULES = [
    "Нижестоящий акт не должен противоречить вышестоящему; при противоречии применяется вышестоящий акт.",
    "Международные договоры, ратифицированные Казахстаном, имеют приоритет перед законами (п. 3 ст. 4 Конституции).",
    "При противоречии норм одного уровня обычно применяется акт, позднее введённый в действие; "
    "специальная норма имеет приоритет перед общей (общий принцип, проверить по конкретному акту).",
    "Нормы кодекса имеют приоритет перед нормами обычного закона того же предмета (кодекс выше по иерархии).",
]


@dataclass(frozen=True)
class Resolution:
    prevails: str | None
    level_a: int | None
    level_b: int | None
    reason: str


def level_of(act: str | None) -> int | None:
    s = (act or "").strip()
    if not s:
        return None
    for lvl, p in _PATTERNS:
        if p.search(s):
            return lvl
    return None


def level_name(level: int | None) -> str:
    return _NAMES.get(level or 0, "уровень не определён")


def resolve(act_a: str, act_b: str) -> Resolution:
    la, lb = level_of(act_a), level_of(act_b)
    if la is None or lb is None:
        return Resolution(None, la, lb, "Уровень одного из актов не определён — приоритет требует проверки.")
    if la == lb:
        return Resolution(None, la, lb, f"Акты одного уровня ({level_name(la)}): применяется позднее введённый "
                                        "в действие или специальная норма — требует проверки по датам и предмету.")
    winner = act_a if la < lb else act_b
    return Resolution(winner, la, lb, f"Приоритет у «{winner}»: {level_name(min(la, lb))} выше, чем "
                                      f"{level_name(max(la, lb))} ({SOURCE}).")


def prompt_block() -> str:
    lines = ["Иерархия НПА РК (от высшего к низшему):"]
    lines += [f"{lvl}. {name}" for lvl, name in LEVELS]
    lines += ["Правила коллизий:"] + [f"- {r}" for r in COLLISION_RULES]
    lines.append("При противоречии норм всегда укажи, какая норма имеет приоритет и почему.")
    return "\n".join(lines)
