MAX_PROFILES = 2


def classify_rules(message: str | None) -> list[Profession]:
    m = normalize(message)
    return [p for p, terms in TERMS.items() if contains_any(m, terms)]


class ProfessionClassifier:
    def __init__(self, classifier: Classifier | None, threshold: float = 0.5):
        self.classifier = classifier
        self.threshold = threshold

    async def classify(self, message: str | None) -> tuple[Profession, ...]:
        found = classify_rules(message)
        if not found and self.classifier is not None and (message or "").strip():
            try:
                pred = await self.classifier.classify(message, LABELS)
                scores = pred.scores or {pred.label: pred.score}
                found = [Profession(k) for k, s in sorted(scores.items(), key=lambda kv: -kv[1])
                         if s >= self.threshold and k != Profession.GENERAL_LAWYER.value]
            except Exception as e:
                log.warning("Profession classification failed, using GENERAL: %s", e)
        return tuple(found[:MAX_PROFILES]) or (Profession.GENERAL_LAWYER,)


def instruction_for(professions: tuple[Profession, ...]) -> str:
    return "".join(INSTRUCTIONS[p] for p in professions)
